import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = dirname(fileURLToPath(import.meta.url));
const wasmDirectory = join(projectRoot, "vendor", "pdfjs-wasm");
const outputFile = join(projectRoot, "vendor", "pdfjs-wasm-data.js");
const filenames = ["jbig2.wasm", "openjpeg.wasm"];
const data = Object.fromEntries(
  filenames.map((filename) => [filename, readFileSync(join(wasmDirectory, filename)).toString("base64")])
);

writeFileSync(
  outputFile,
  `// Generated by generate-wasm-data.mjs. Do not edit by hand.\nwindow.PDFJS_WASM_DATA = Object.freeze(${JSON.stringify(data)});\n`
);
